def main() -> None:

    provider = choose_provider()
    client = build_client(provider)
    model = provider["model"]

    fallback_model = None
    fallback_client = None

    if provider["name"] != "Ollama (локальный)":
        try:
            fallback_provider = PROVIDERS["3"]
            fallback_client = build_client(fallback_provider)
            fallback_model = fallback_provider["model"]
            print(f"{provider['name']} доступен. Модель: {model}")
        except Exception as e:
            print(f"Fallback Ollama недоступен: {e}")

    if fallback_model is None:
        print(f"\nПровайдер: {provider['name']}, модель: {model}")

    # ИСПРАВЛЕНО: Создаем пустой контекст диалога, чтобы не было NameError
    messages = [
         {"role": "system", "content": "Ты — опытный Python-разработчик."},# Промт - только промт, если я хочу сама вводить запрос в командной строке.
    ]
    #messages = [
    #     {"role": "system", "content": "Ты — опытный Python-разработчик."},# Промт
    #     {"role": "user", "content": "Объясни декораторы в 3 предложениях."} # Здесь тестовый вопрос если мне надо фикс вопрос и овтет, тогда надо будет убрать из main цикл while True и команду input(), чтобы скрипт не останавливался и не ждал, пока что-то напечатю. Тогда он берёт этот готовый список messages и сразу отправляет его в функцию call_with_fallback.
    # ]

    print("Введите сообщение. Для выхода используйте exit, quit или выход.")
    start_time = time.time()  
    ttft_time = None  # Сюда запишем время первого токена
    
    while True:
        user_input = input("\nВы: ").strip()
        if user_input.lower() in ("exit", "quit", "выход"):
            print("Диалог завершён.")
            break

        if not user_input:
            print("Пустой ввод пропущен.")
            continue

        messages.append({"role": "user", "content": user_input})

        try:
            stream, used_model = call_with_fallback(
                primary_client=client,
                primary_model=model,
                fallback_client=fallback_client,
                fallback_model=fallback_model,
                messages=messages,
                temperature=2, #1, 0 или 0.7 или 1.5 + Top P можно попробовать добавить и penalty
                max_tokens=200,
            )
        except RateLimitError:
            print("  [ERROR] Превышен лимит запросов. Попробуйте позже.")
            messages.pop()  # убираем неотправленное сообщение
            continue
        except APIConnectionError:
            print("  [ERROR] Нет подключения к API. Проверьте интернет.")
            messages.pop()
            continue
        except APIError as e:
            print(f"  [ERROR] Ошибка API: {e.status_code}")
            messages.pop()
            continue
        except Exception as e:
            print(f"  [ERROR] {e}")
            messages.pop()
            continue

        print(f"\n[Отвечает модель: {used_model}]")
        print("Ассистент: ", end="")
        full_response = ""
        usage = None
        for chunk in stream:
            # ИСПРАВЛЕНО: Безопасное чтение контента чанка. Защита от пустых списков choices в финальном чанке с Usage!
            if hasattr(chunk, "choices") and chunk.choices:
                delta = chunk.choices[0].delta.content or ""
                if delta:
                    # --- ФИКСИРУЕМ TTFT ПРИ ПЕРВОМ ПОЯВЛЕНИИ ТЕКСТА ---
                    if ttft_time is None:
                        ttft_time = time.time() - start_time
                    print(delta, end="", flush=True)
                    full_response += delta
            
            if hasattr(chunk, "usage") and chunk.usage:
                usage = chunk.usage

        print()  # Печатаем перевод строки после завершения ответа
        # ЗАМЕР ПОЛНОГО ВРЕМЕНИ ВЫПОЛНЕНИЯ
        total_time = time.time() - start_time

        # Выводим красивую статистику по времени
        print("\n" + "="*40)
        print("МЕТРИКИ СКОРОСТИ СТРИМИНГА:")
        if ttft_time is not None:
            print(f"   • Время до первого токена (TTFT): {ttft_time:.3f} сек")
        else:
            print(f"   • Время до первого токена (TTFT): Не удалось замерить (ответ пустой)")
        print(f"   • Полное время генерации (Total): {total_time:.3f} сек")
        print("="*40)
    
        if usage:
            print(
                f"[Токены: запрос={usage.prompt_tokens}, "
                f"ответ={usage.completion_tokens}, "
                f"всего={usage.total_tokens}]"
            )
            if usage.completion_tokens and total_time > 0:
                speed = usage.completion_tokens / total_time
                print(f"[Скорость генерации: {speed:.1f} токенов/сек]")
        messages.append({"role": "assistant", "content": full_response})


if __name__ == "__main__":
    main()


    
