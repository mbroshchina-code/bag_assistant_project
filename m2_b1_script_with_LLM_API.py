def call_llm_with_retry(client: Any, model: str, messages: list[dict], temperature: float = 1.0, max_tokens: int = 500) -> Any:
    """Вызов LLM с автоматическим retry через tenacity.

    Повторяет запрос при:
    - RateLimitError (429) — до 3 раз с экспоненциальной задержкой  # исправлено до 3 раз
    - APIStatusError с кодом 5xx — серверные ошибки
    """
    from tenacity import (
        retry,
        wait_exponential,
        stop_after_attempt,
        retry_if_exception_type,
    )
    from openai import RateLimitError, APIStatusError

    # Функция-предикат: повторяем на 429 и 5xx
    def should_retry(error: BaseException) -> bool:
        if isinstance(error, RateLimitError):
            return True
        if isinstance(error, APIStatusError) and error.status_code >= 500:
            return True
        return False

    @retry( # ИСПРАВЛЕНО: tenacity теперь реагирует ТОЛЬКО на сетевые ошибки API, но НЕ на ошибки нашего Python-кода (типа IndexError)
        wait=wait_exponential(multiplier=1, min=1, max=10),
        stop=stop_after_attempt(3),
        retry=retry_if_exception_type((RateLimitError, APIStatusError, APIConnectionError)),
        reraise=True
    )
    def _call() -> Any:
        return client.chat.completions.create(
            model=model,
            messages=messages, 
            stream=True, # Без стриминга понятия TTFT (время до первого токена) и Total Time (полное время) сливаются в одну точку
            stream_options={"include_usage": True},
            temperature=temperature, #добавила
            max_tokens=max_tokens,#добавила
        )

    return _call()


def call_with_fallback(
    primary_client: Any,
    primary_model: str,
    fallback_client: Any | None,
    fallback_model: str | None,
    messages: list[dict],
    temperature: float = 1.0, #добавила
    max_tokens: int = 500, #добавила
) -> Any:
    """Пробует основного провайдера, при неудаче — fallback.

    Возвращает stream от первого успешного провайдера.
    """

    try:
        return call_llm_with_retry(primary_client, primary_model, messages), primary_model
    except (RateLimitError, APIError, APIConnectionError) as e:
        print(f"  [Основной провайдер недоступен: {e}]")

        if fallback_client and fallback_model:
            print(f"  [Переключаюсь на fallback: {fallback_model}]")
            try:
                return call_llm_with_retry(fallback_client, fallback_model, messages), fallback_model
            except Exception as fallback_err:
                raise RuntimeError(
                    f"Оба провайдера недоступны. Fallback: {fallback_err}"
                ) from fallback_err
        raise



def build_client(provider: dict) -> Any:
    """Создаёт OpenAI-совместимый клиент для указанного провайдера."""
    if provider["env_key"]:
        api_key = os.getenv(provider["env_key"])
        if not api_key:
            raise SystemExit(
                f"Не найден {provider['env_key']} в переменных окружения или .env"
            )
    else:
        api_key = provider["api_key"]

    return OpenAI(api_key=api_key, base_url=provider["base_url"])

